const FANUC_LATHE = `// Fanuc-style lathe: X as a diameter, G99 feed per revolution, G96 constant surface speed under a G50 limit,
// T0101 tool and offset, G32 threading, G28 U0 W0 home.
post fanuc-lathe
name Fanuc-style lathe (.nc)
extension nc
line-numbers 10
decimal-point yes
canned-cycles no
machine lathe
lathe-x diameter
modal motion G0 G1 G32

on start
  raw %
  raw O{program|pad:4} ({name|safe|upper|cut:30})
${LATHE_HEADER}  emit G21 G18 G40 G80 G99
  emit G28 U0.
  emit G28 W0.
end
${LATHE_COMMON}
on tool-change
  if previous
    if cool
      emit M9
    end
    set cool no
    emit M5
    emit G28 U0.
    emit G28 W0.
    reset X Z motion
  end
  emit T{tool.number|pad:2}{tool.number|pad:2}
end

on spindle
  if spin.mode == css
    emit G50 S{spin.max}
    emit G96 S{spin.css} M3
  else
    emit G97 S{rpm} M3
  end
end

on thread
  emit G32~ X{x}~ Z{z}~ F{thread.lead}~!
end

on end
  if cool
    emit M9
  end
  emit M5
  emit G28 U0.
  emit G28 W0.
  emit M30
  raw %
end
`;

