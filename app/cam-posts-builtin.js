/**
 * cam-posts-builtin.js — the three posts PartCraft ships, written in its own post format (cam-postdef.js).
 * Each one writes exactly what the older code in cam-post.js wrote (the tests compare byte for byte), so a person
 * can copy one into the post editor and change it. The header comments are file content: ASCII, English.
 */
const COMMON_HEAD = `
on operation
  if op.type
    comment {op.name} - {op.type}
  else
    comment {op.name}
  end
end

on spindle
  emit S{rpm} M3
end

on coolant-on
  if coolant.mode == mist
    emit M7
  else
    emit M8
  end
end

on rapid
  if moved
    emit G0~ X{x}~ Y{y}~ Z{z}~
  end
end

on feed
  if moved
    emit G1~ X{x}~ Y{y}~ Z{z}~ F{f}~
  end
end

on arc
  emit G{arc.g}~! X{x}~! Y{y}~! Z{z}~ I{arc.i} J{arc.j} F{f}~
end
`;

// 0.11 CAM.7: rotary axes. These events only run for a machine with rotary axes (Setup) or an operation that needs them, so a
// 3-axis program is written exactly as before.
const ROTARY_MOVES = `
on rapid-rotary
  if moved
    emit G0~ X{x}~ Y{y}~ Z{z}~ A{rot.a}~ B{rot.b}~ C{rot.c}~
  end
end

on feed-rotary
  if moved
    if inverse
      emit G93~ G1~ X{x}~ Y{y}~ Z{z}~ A{rot.a}~ B{rot.b}~ C{rot.c}~ F{invf}~!
    else
      emit G94~ G1~ X{x}~ Y{y}~ Z{z}~ A{rot.a}~ B{rot.b}~ C{rot.c}~ F{f}~!
    end
  end
end

on rotary-end
  emit G94~
  reset F
end
`;
const ROTARY_NOTE = `  if rotary
    if tcp
      comment Rotary axes {kin}: positions for this machine as described in Setup, tool tip control on
    else
      comment Rotary axes {kin}: X Y Z are written as the turned table carries them, about X{pivot.x} Y{pivot.y} Z{pivot.z}
    end
  end
`;

const HEADER_COMMENTS = `
  comment Generated by PartCraft, lab build - verify before running
  comment Program {program}: {name}
  if stock.kind == cylinder
    comment Stock: cylinder D{stock.d} x {stock.sz} mm
  else
    comment Stock: box {stock.sx} x {stock.sy} x {stock.sz} mm
  end
  comment Stock min X{stock.minx} Y{stock.miny} Z{stock.minz} max X{stock.maxx} Y{stock.maxy} Z{stock.maxz}
  comment Work offset G54: {setup.origin}; tool axis {setup.axis}
  for tool in tools
    comment T{tool.number} {tool.desc} flutes {tool.flutes} flute length {tool.fluteLen}
  end
  comment Units mm
`;

const TOOL_STOP = `
  if previous
    if cool
      emit M9
    end
    set cool no
    emit M5
  end
`;

const CANNED = `
on cycle-start
  if cycle.kind == drill
    set code G81
  else
    if cycle.kind == peck
      set code G83
    else
      set code G73
    end
  end
  reset retplane Z R Q
end

on cycle-hole
  if hole.return == r
    word G99~
  else
    word G98~
  end
  if hole.first
    word {code}
  end
  word X{hole.x}~! Y{hole.y}~! Z{hole.z}~ R{hole.r}~
  if code != G81
    word Q{hole.q}~
  end
  if hole.first
    word F{feed}~!
  end
  emit
end

on cycle-end
  emit G80
  reset motion
  if hole.return == r
    set at.z hole.r
  else
    set at.z cycle.init
  end
end
`;

const FANUC = `// Fanuc-style control: % and O number, N line numbers, decimal points, G28 home, G43 tool length, canned cycles.
post fanuc
name Fanuc-style control (.nc)
extension nc
line-numbers 10
decimal-point yes
canned-cycles yes
modal motion G0 G1 G2 G3
modal retplane G98 G99
modal feedmode G93 G94

on start
  raw %
  raw O{program|pad:4} ({name|safe|upper|cut:30})
${HEADER_COMMENTS}${ROTARY_NOTE}  emit G90 G94 G17 G21 G40 G49 G80
  emit G28 G91 Z0.
  emit G90
  emit G54
end
${COMMON_HEAD}
on tool-change
${TOOL_STOP}  emit T{tool.number} M6
end

on index
  comment Turn to the tool direction
  emit G49
  emit G28 G91 Z0.
  emit G90
  emit G0~! A{rot.a}~! B{rot.b}~! C{rot.c}~!
  emit G0~! X{first.x}~! Y{first.y}~!
  reset Z
  set offset none
end

on approach
  if offset != tool.number
    if tcp
      emit G0~! G43.4 Z{first.z}~! H{tool.number}
    else
      emit G0~! G43 Z{first.z}~! H{tool.number}
    end
    set offset tool.number
  else
    do rapid at.x??first.x at.y??first.y first.z
  end
end
${CANNED}${ROTARY_MOVES}
on probe-move
  emit G31 X{x}~ Y{y}~ Z{z}~ F{f}~!
  raw #10{probe.n}=#506{probe.k}
end

on probe-set
  if probe.action == set
    if probe.kind == "z"
      raw #5223=#5223+[#101-[{probe.expect}]]
    end
    if probe.kind == "x"
      raw #5221=#5221+[#101-[{probe.expect}]]
    end
    if probe.kind == "y"
      raw #5222=#5222+[#101-[{probe.expect}]]
    end
    if probe.kind == centre
      raw #5221=#5221+[[#101+#102]/2.-[{probe.cx}]]
      raw #5222=#5222+[[#103+#104]/2.-[{probe.cy}]]
    end
    reset X Y Z
  else
    comment Measured only, nothing set: the difference is in 110, and 111 for a centre
    if probe.kind == centre
      raw #110=[#101+#102]/2.-[{probe.cx}]
      raw #111=[#103+#104]/2.-[{probe.cy}]
    else
      raw #110=#101-[{probe.expect}]
    end
  end
end

on end
  if cool
    emit M9
  end
  emit M5
  emit G28 G91 Z0.
  emit G90
  emit M30
  raw %
end
`;

const LINUXCNC = `// LinuxCNC: % wrapper, no line numbers, G53 G0 Z0 (machine Z top), G43 tool length, canned cycles.
post linuxcnc
name LinuxCNC (.ngc)
extension ngc
line-numbers off
decimal-point no
canned-cycles yes
modal motion G0 G1 G2 G3
modal retplane G98 G99
modal feedmode G93 G94

on start
  raw %
${HEADER_COMMENTS}${ROTARY_NOTE}  emit G17 G21 G90 G94 G40 G49 G80
  emit G53 G0 Z0
  emit G54
end
${COMMON_HEAD}
on tool-change
${TOOL_STOP}  emit T{tool.number} M6
end

on index
  comment Turn to the tool direction
  emit G49
  emit G53 G0 Z0
  emit G0~! A{rot.a}~! B{rot.b}~! C{rot.c}~!
  emit G0~! X{first.x}~! Y{first.y}~!
  reset Z
  set offset none
end

on approach
  if offset != tool.number
    if tcp
      emit G0~! G43.4 Z{first.z}~! H{tool.number}
    else
      emit G0~! G43 Z{first.z}~! H{tool.number}
    end
    set offset tool.number
  else
    do rapid at.x??first.x at.y??first.y first.z
  end
end
${CANNED}${ROTARY_MOVES}
on probe-move
  emit G38.2 X{x}~ Y{y}~ Z{z}~ F{f}~!
  raw #<_pc{probe.n}>=#506{probe.k}
  reset motion
end

on probe-set
  if probe.action == set
    if probe.kind == "z"
      raw G10 L2 P1 Z[#5223+#<_pc1>-[{probe.expect}]]
    end
    if probe.kind == "x"
      raw G10 L2 P1 X[#5221+#<_pc1>-[{probe.expect}]]
    end
    if probe.kind == "y"
      raw G10 L2 P1 Y[#5222+#<_pc1>-[{probe.expect}]]
    end
    if probe.kind == centre
      raw G10 L2 P1 X[#5221+[#<_pc1>+#<_pc2>]/2-[{probe.cx}]] Y[#5222+[#<_pc3>+#<_pc4>]/2-[{probe.cy}]]
    end
    reset X Y Z
  else
    if probe.kind == centre
      raw #<_pc_dx>=[[#<_pc1>+#<_pc2>]/2-[{probe.cx}]]
      raw #<_pc_dy>=[[#<_pc3>+#<_pc4>]/2-[{probe.cy}]]
      raw (DEBUG, PartCraft probe: centre off by X #<_pc_dx> Y #<_pc_dy>)
    else
      raw #<_pc_d>=[#<_pc1>-[{probe.expect}]]
      raw (DEBUG, PartCraft probe: off by #<_pc_d>)
    end
  end
end

on end
  if cool
    emit M9
  end
  emit M5
  emit G53 G0 Z0
  emit M2
  raw %
end
`;

const GRBL = `// GRBL 1.1: no % or O, no M6 or tool length offsets (a tool change is M5 + M0 with the tool in a comment),
// holes written as the G0/G1 moves they stand for, M30.
post grbl
name GRBL (.nc)
extension nc
line-numbers off
decimal-point no
canned-cycles no
modal motion G0 G1 G2 G3
modal feedmode G93 G94

on start
${HEADER_COMMENTS}${ROTARY_NOTE}  emit G17 G21 G90 G94
  emit G54
end
${COMMON_HEAD}
on tool-change
${TOOL_STOP}  comment Tool change: T{tool.number} {tool.desc}
  if previous
    emit M0
  end
  emit T{tool.number}
end

on index
  comment Turn to the tool direction - GRBL 1.1 has no rotary axes, this needs a build that has them
  emit G53 G0 Z0
  emit G0~! A{rot.a}~! B{rot.b}~! C{rot.c}~!
  emit G0~! X{first.x}~! Y{first.y}~!
  reset Z
end

on approach
  if at.z != first.z
    emit G0~! Z{first.z}~!
  end
end
${ROTARY_MOVES}
on probe-move
  emit G38.2 X{x}~ Y{y}~ Z{z}~ F{f}~!
  reset motion
end

on probe-set
  if probe.kind == centre
    comment GRBL has no variables, it cannot work out a centre - nothing was set
  else
    if probe.action == set
      if probe.kind == "z"
        emit G10 L20 P1 Z{probe.expect}
      end
      if probe.kind == "x"
        emit G10 L20 P1 X{probe.expect}
      end
      if probe.kind == "y"
        emit G10 L20 P1 Y{probe.expect}
      end
      reset X Y Z
    else
      comment Measured only, nothing set - read the probe position the control reports
    end
  end
end

on end
  if cool
    emit M9
  end
  emit M5
  emit M30
end
`;

