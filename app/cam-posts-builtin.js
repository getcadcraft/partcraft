/**
 * cam-posts-builtin.js — the three posts PartCraft ships, written in its own post format (cam-postdef.js).
 * Each one writes exactly what the older code in cam-post.js wrote (the tests compare byte for byte), so a person
 * can copy one into the post editor and change it. The header comments are file content: ASCII, English.
 */
const COMMON_HEAD = `
on operation
  if op.type
    comment {op.name} - {op.type}
  else
    comment {op.name}
  end
end

on spindle
  emit S{rpm} M3
end

on coolant-on
  if coolant.mode == mist
    emit M7
  else
    emit M8
  end
end

on rapid
  if moved
    emit G0~ X{x}~ Y{y}~ Z{z}~
  end
end

on feed
  if moved
    emit G1~ X{x}~ Y{y}~ Z{z}~ F{f}~
  end
end

on arc
  emit G{arc.g}~! X{x}~! Y{y}~! Z{z}~ I{arc.i} J{arc.j} F{f}~
end
`;

const HEADER_COMMENTS = `
  comment Generated by PartCraft, lab build - verify before running
  comment Program {program}: {name}
  if stock.kind == cylinder
    comment Stock: cylinder D{stock.d} x {stock.sz} mm
  else
    comment Stock: box {stock.sx} x {stock.sy} x {stock.sz} mm
  end
  comment Stock min X{stock.minx} Y{stock.miny} Z{stock.minz} max X{stock.maxx} Y{stock.maxy} Z{stock.maxz}
  comment Work offset G54: {setup.origin}; tool axis {setup.axis}
  for tool in tools
    comment T{tool.number} {tool.desc} flutes {tool.flutes} flute length {tool.fluteLen}
  end
  comment Units mm
`;

const TOOL_STOP = `
  if previous
    if cool
      emit M9
    end
    set cool no
    emit M5
  end
`;

const CANNED = `
on cycle-start
  if cycle.kind == drill
    set code G81
  else
    if cycle.kind == peck
      set code G83
    else
      set code G73
    end
  end
  reset retplane Z R Q
end

on cycle-hole
  if hole.return == r
    word G99~
  else
    word G98~
  end
  if hole.first
    word {code}
  end
  word X{hole.x}~! Y{hole.y}~! Z{hole.z}~ R{hole.r}~
  if code != G81
    word Q{hole.q}~
  end
  if hole.first
    word F{feed}~!
  end
  emit
end

on cycle-end
  emit G80
  reset motion
  if hole.return == r
    set at.z hole.r
  else
    set at.z cycle.init
  end
end
`;

const FANUC = `// Fanuc-style control: % and O number, N line numbers, decimal points, G28 home, G43 tool length, canned cycles.
post fanuc
name Fanuc-style control (.nc)
extension nc
line-numbers 10
decimal-point yes
canned-cycles yes
modal motion G0 G1 G2 G3
modal retplane G98 G99

on start
  raw %
  raw O{program|pad:4} ({name|safe|upper|cut:30})
${HEADER_COMMENTS}  emit G90 G94 G17 G21 G40 G49 G80
  emit G28 G91 Z0.
  emit G90
  emit G54
end
${COMMON_HEAD}
on tool-change
${TOOL_STOP}  emit T{tool.number} M6
end

on approach
  if offset != tool.number
    emit G0~! G43 Z{first.z}~! H{tool.number}
    set offset tool.number
  else
    do rapid at.x??first.x at.y??first.y first.z
  end
end
${CANNED}
on end
  if cool
    emit M9
  end
  emit M5
  emit G28 G91 Z0.
  emit G90
  emit M30
  raw %
end
`;

const LINUXCNC = `// LinuxCNC: % wrapper, no line numbers, G53 G0 Z0 (machine Z top), G43 tool length, canned cycles.
post linuxcnc
name LinuxCNC (.ngc)
extension ngc
line-numbers off
decimal-point no
canned-cycles yes
modal motion G0 G1 G2 G3
modal retplane G98 G99

on start
  raw %
${HEADER_COMMENTS}  emit G17 G21 G90 G94 G40 G49 G80
  emit G53 G0 Z0
  emit G54
end
${COMMON_HEAD}
on tool-change
${TOOL_STOP}  emit T{tool.number} M6
end

on approach
  if offset != tool.number
    emit G0~! G43 Z{first.z}~! H{tool.number}
    set offset tool.number
  else
    do rapid at.x??first.x at.y??first.y first.z
  end
end
${CANNED}
on end
  if cool
    emit M9
  end
  emit M5
  emit G53 G0 Z0
  emit M2
  raw %
end
`;

const GRBL = `// GRBL 1.1: no % or O, no M6 or tool length offsets (a tool change is M5 + M0 with the tool in a comment),
// holes written as the G0/G1 moves they stand for, M30.
post grbl
name GRBL (.nc)
extension nc
line-numbers off
decimal-point no
canned-cycles no
modal motion G0 G1 G2 G3

on start
${HEADER_COMMENTS}  emit G17 G21 G90 G94
  emit G54
end
${COMMON_HEAD}
on tool-change
${TOOL_STOP}  comment Tool change: T{tool.number} {tool.desc}
  if previous
    emit M0
  end
  emit T{tool.number}
end

on approach
  if at.z != first.z
    emit G0~! Z{first.z}~!
  end
end

on end
  if cool
    emit M9
  end
  emit M5
  emit M30
end
`;

export const BUILTIN_POSTS = { fanuc: FANUC, grbl: GRBL, linuxcnc: LINUXCNC };

/** A built-in post as a text of one's own: the `post` and `name` lines replaced (and a leading comment saying where it came from). */
export function postCopy(kind, id, name) {
  const text = BUILTIN_POSTS[kind];
  if (text === undefined) throw new Error('postCopy: unknown post');   // i18n-ignore: a programming error
  return text.replace(/^post .*$/m, 'post ' + id).replace(/^name .*$/m, 'name ' + String(name).replace(/[\r\n]/g, ' '));
}
/** A post with every event in it and nothing in the events: the place to start a new one from. */
export function blankPost(id, name) {
  return `// A post: the text of the program, one event at a time. See the reference under the editor.
post ${id}
name ${String(name).replace(/[\r\n]/g, ' ')}
extension nc
line-numbers off
decimal-point no
canned-cycles no
modal motion G0 G1 G2 G3

on start
  comment Program {program}: {name}
  emit G21 G90 G17
end

on tool-change
  emit T{tool.number} M6
end

on spindle
  emit S{rpm} M3
end

on rapid
  if moved
    emit G0~ X{x}~ Y{y}~ Z{z}~
  end
end

on feed
  if moved
    emit G1~ X{x}~ Y{y}~ Z{z}~ F{f}~
  end
end

on arc
  emit G{arc.g}~! X{x}~! Y{y}~! Z{z}~ I{arc.i} J{arc.j} F{f}~
end

on end
  emit M5
  emit M30
end
`;
}

/** A small program that runs every event of a post (two tools, a tool change, coolant, an arc, a peck cycle): the editor's preview. */
export function samplePostProgram() {
  const tools = [
    { id: 's1', number: 1, kind: 'flat', d: 6, flutes: 3, fluteLen: 20, name: '' },
    { id: 's2', number: 5, kind: 'drill', d: 5, flutes: 2, fluteLen: 40, angle: 118, name: '' },
  ];
  const hole = (x, y) => ({ at: [x, y], top: 0, z: -12, r: 2, q: 4, ret: 'r' });
  return {
    setup: { program: 1001, coolant: 'flood', axis: '+y', origin: 'stock-top-min' },
    model: { stock: { kind: 'box', min: [0, 0, -15], max: [60, 40, 0], c: null, r: null } },
    paths: [
      { op: { id: 'a', name: 'Pocket 1', type: 'pocket' }, tool: tools[0], speeds: { rpm: 12000 }, moves: [
        { k: 'rapid', p: [10, 10, 10] }, { k: 'feed', p: [10, 10, -3], f: 300 }, { k: 'feed', p: [40, 10, -3], f: 900 },
        { k: 'arc', p: [50, 20, -3], c: [40, 20], sw: Math.PI / 2, f: 900 }, { k: 'rapid', p: [50, 20, 10] }] },
      { op: { id: 'b', name: 'Drill 1', type: 'drill' }, tool: tools[1], speeds: { rpm: 3000 }, moves: [
        { k: 'rapid', p: [15, 30, 10] }, { k: 'cycle', kind: 'peck', init: 10, f: 120, holes: [hole(15, 30), hole(30, 30)] }] },
    ],
  };
}
