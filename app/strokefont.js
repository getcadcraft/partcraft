const BOX = [4, [[[0, 0], [4, 0], [4, 7], [0, 7], [0, 0]]]];

export const hasGlyph = (ch) => !!G[ch];

/** The advance of a string, in drawing units. */
export function textWidth(text, h = 1, wf = 1) {
  let w = 0;
  for (const ch of String(text)) w += ((G[ch] || BOX)[0] + GAP);
  return Math.max(0, w - GAP) * (h / 9) * (wf || 1);
}

/** Polylines of a string (see the header). */
export function textStrokes(text, { h = 1, wf = 1, oblique = 0 } = {}) {
  const s = h / 9, sx = s * (wf || 1), sh = Math.tan(oblique || 0);
  const lines = [];
  let x = 0, missing = 0;
  for (const ch of String(text)) {
    let g = G[ch];
    if (!g) { if (/\s/.test(ch)) g = G[' ']; else { g = BOX; missing++; } }
    for (const l of g[1]) lines.push(l.map(([px, py]) => [x + px * sx + py * s * sh, py * s]));
    x += (g[0] + GAP) * sx;
  }
  return { lines, width: Math.max(0, x - GAP * sx), missing };
}

/** TEXT / ATTRIB value: the %% control codes. */
export function cleanDxfText(s) {
  return String(s ?? '').replace(/%%(\d{3}|[dDpPcC%uUoO])/g, (m, c) => {
    if (/^\d{3}$/.test(c)) return String.fromCharCode(parseInt(c, 10));
    const k = c.toLowerCase();
    return k === 'd' ? '°' : k === 'p' ? '±' : k === 'c' ? 'Ø' : k === '%' ? '%' : '';
  });
}

/** MTEXT value → plain text with "\n" between lines. */
export function cleanMtext(s) {
  let t = String(s ?? '');
  t = t.replace(/\\U\+([0-9a-fA-F]{4})/g, (m, h) => String.fromCharCode(parseInt(h, 16)));
  t = t.replace(/\\S([^;]*?)[\^/#]([^;]*?);/g, '$1/$2');                    // stacked fraction a^b, a/b, a#b
  t = t.replace(/\\[fFcCHhWwTtQqAapP][^;\\]*;/g, (m) => (/^\\[pP]/.test(m) && m.length === 2 ? m : m[1] === 'P' && m === '\\P;' ? '\n' : ''));
  t = t.replace(/\\P/g, '\n').replace(/\\~/g, ' ').replace(/\\[LlOoKkNX]/g, '');
  t = t.replace(/\\\\/g, '\u0001').replace(/\\\{/g, '\u0002').replace(/\\\}/g, '\u0003');
  t = t.replace(/[{}]/g, '');
  t = t.replace(/\u0001/g, '\\').replace(/\u0002/g, '{').replace(/\u0003/g, '}');
  return cleanDxfText(t);
}
