/**
 * strokefont.js — a small single-stroke font of our own, for drawing text from imported drawings as edges (0.4 M1).
 * No DOM, no dependencies. Glyphs are drawn on a grid where the capital height is 9, the x-height 6 and descenders go
 * to −3; each glyph is a list of polylines plus its width. Arcs are elliptical arcs sampled every 15°.
 *
 *   textStrokes(text, {h, wf, oblique}) → {lines: [[[x, y]…]…], width, missing}
 *     text-local coordinates: origin at the left end of the baseline, x along the text, y up, in drawing units
 *     (h = capital height, wf = width factor, oblique = slant in radians). `missing` counts characters the font has
 *     no glyph for (drawn as a small box).
 *   textWidth(text, h, wf) → the advance of the whole string
 *   cleanDxfText(s) → TEXT/ATTRIB value with %%d %%p %%c %%% decoded and %%u %%o dropped
 *   cleanMtext(s) → MTEXT value as plain lines (format codes removed, \P → newline, stacked fractions as a/b)
 */

const GAP = 2;   // space between glyphs, grid units

/** Points of an elliptical arc, degrees, a0 → a1 (counter-clockwise when a1 > a0, clockwise when a1 < a0). */
function E(cx, cy, rx, ry, a0, a1) {
  const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / 15));
  const out = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return out;
}
