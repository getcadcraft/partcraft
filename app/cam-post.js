/**
 * cam-post.js — G-code from a PartCraft program (DOM-free): the posts and plain toolpath exports.
 *
 *   post(program, {post fanuc|grbl|linuxcnc|custom:<id>, posts, name}) → {text, ext, post}
 *   toolpathCsv(program) · toolpathJson(program)
 *
 * Since 0.7 (LC.15) the posts are TEXT in PartCraft's own post format (cam-postdef.js, the built-ins in cam-posts-builtin.js) and
 * post() runs them; a study can carry posts of its own (posts: [{id, text}], chosen as `custom:<id>`). postLegacy() below is the
 * older code the three built-in texts were written from: it is kept as the reference the tests compare them with, byte for byte.
 *
 * Every post: header comments (program, date-free so the output is reproducible, stock, work offset, tools,
 * "Generated by PartCraft (lab build) — verify before running"), G90 G94 G17 G21 and G54, tool changes, spindle
 * M3 S, coolant, G0/G1, arcs G2/G3 with I J (incremental centre, XY plane), a safe end. Coordinates in mm with
 * 3 decimals (1 µm); the same numbers in every post. Differences, and only these:
 *   fanuc     % and O number, N line numbers, decimal point on every number (X10.), G28 G91 Z0. home at start
 *             and end, T M6 + G0 G43 Z H, canned cycles G81/G83/G73 with G98/G99 and G80, M30.
 *   linuxcnc  % wrapper, no line numbers, G53 G0 Z0 (machine Z top) at the start and end, T M6 + G43 H,
 *             canned cycles G81/G83/G73 with G98/G99 and G80, M2.
 *   grbl      no % / O / N, no M6 or tool-length offsets (GRBL 1.1 has neither): a tool change is M5 + M0 (pause)
 *             with the tool in a comment; canned cycles are written as the G0/G1 moves they stand for; M30.
 */
import { expandCycle, segments } from './cam-paths.js';
import { describeTool } from './cam-tools.js';
import { ORIGINS } from './cam.js';
import { t } from './i18n.js';
import { q, num, safeComment } from './cam-fmt.js';
import { parsePost, renderPost } from './cam-postdef.js';
import { BUILTIN_POSTS } from './cam-posts-builtin.js';

export { num };
export const EXT = { fanuc: 'nc', grbl: 'nc', linuxcnc: 'ngc' };
export { parsePost, renderPost };

/** The three posts as code — kept as the reference the text posts (cam-posts-builtin.js) are tested against, byte for byte. */
export function postLegacy(program, { post: kind = 'grbl', name = 'Part' } = {}) {
  const fanuc = kind === 'fanuc', grbl = kind === 'grbl', lcnc = kind === 'linuxcnc';
  if (!fanuc && !grbl && !lcnc) throw new Error(t('xch.cam.unknown_post'));
  const setup = program.setup;
  const out = [];
  let n = 0;
  const line = (s) => { if (fanuc) { n += 10; out.push('N' + n + ' ' + s); } else out.push(s); };
  const comment = (s) => out.push('(' + safeComment(s) + ')');
  const F = (v) => num(v, fanuc);
  const paths = program.paths.filter((p) => p.moves && p.moves.length);
  // header (G-code comments below are file content: ASCII, English)
  if (fanuc || lcnc) out.push('%');
  if (fanuc) out.push('O' + String(setup.program).padStart(4, '0') + ' (' + safeComment(name).toUpperCase().slice(0, 30) + ')');
  comment('Generated by PartCraft, lab build - verify before running');   // i18n-ignore: G-code comment
  comment('Program ' + setup.program + ': ' + name);
  const s = program.model.stock;
  const C = (v) => num(v);
  // i18n-ignore: G-code comment
  comment(s.kind === 'cylinder' ? `Stock: cylinder D${C(2 * s.r)} x ${C(s.max[2] - s.min[2])} mm` : `Stock: box ${C(s.max[0] - s.min[0])} x ${C(s.max[1] - s.min[1])} x ${C(s.max[2] - s.min[2])} mm`);
  // i18n-ignore: G-code comment
  comment(`Stock min X${C(s.min[0])} Y${C(s.min[1])} Z${C(s.min[2])} max X${C(s.max[0])} Y${C(s.max[1])} Z${C(s.max[2])}`);
  // i18n-ignore: G-code comment
  comment('Work offset G54: ' + (ORIGINS[setup.origin] || setup.origin) + '; tool axis ' + setup.axis);
  const used = [];
  for (const p of paths) if (p.tool && !used.find((t) => t.id === p.tool.id)) used.push(p.tool);
  // i18n-ignore: G-code comment
  for (const t of used) comment(`T${t.number} ${describeTool(t).replace('⌀', 'D')} flutes ${t.flutes} flute length ${num(t.fluteLen)}`);
  comment('Units mm');   // i18n-ignore: G-code comment
  line(fanuc ? 'G90 G94 G17 G21 G40 G49 G80' : lcnc ? 'G17 G21 G90 G94 G40 G49 G80' : 'G17 G21 G90 G94');
  if (fanuc) { line('G28 G91 Z0.'); line('G90'); }
  if (lcnc) line('G53 G0 Z0');
  line('G54');
  // motion
  const st = { g: null, x: null, y: null, z: null, f: null };
  const coolOn = setup.coolant === 'mist' ? 'M7' : setup.coolant === 'flood' ? 'M8' : null;
  let tool = null, rpm = null;
  const axes = (p, force = false) => {
    let w = '';
    if (force || st.x === null || q(p[0]) !== q(st.x)) w += ' X' + F(p[0]);
    if (force || st.y === null || q(p[1]) !== q(st.y)) w += ' Y' + F(p[1]);
    if (force || st.z === null || q(p[2]) !== q(st.z)) w += ' Z' + F(p[2]);
    return w;
  };
  const set = (p) => { st.x = p[0]; st.y = p[1]; st.z = p[2]; };
  const move = (m) => {
    if (m.k === 'rapid') {
      const w = axes(m.p);
      if (!w) return;
      line(((st.g === 0 ? '' : 'G0') + w).trim());
      st.g = 0; set(m.p);
    } else if (m.k === 'feed') {
      const w = axes(m.p);
      if (!w) return;
      const fw = q(m.f) !== st.f ? ' F' + F(m.f) : '';
      line(((st.g === 1 ? '' : 'G1') + w + fw).trim());
      st.g = 1; st.f = q(m.f); set(m.p);
    } else if (m.k === 'arc') {
      const g = m.sw < 0 ? 2 : 3;
      let w = ' X' + F(m.p[0]) + ' Y' + F(m.p[1]);
      if (st.z === null || q(m.p[2]) !== q(st.z)) w += ' Z' + F(m.p[2]);
      // I J from the start as written (rounded), to the exact centre, rounded: the end radius stays within 1 µm
      const i = q(m.c[0] - q(st.x)), j = q(m.c[1] - q(st.y));
      const fw = q(m.f) !== st.f ? ' F' + F(m.f) : '';
      line('G' + g + w + ' I' + F(i) + ' J' + F(j) + fw);
      st.g = g; st.f = q(m.f); set(m.p);
    }
  };
  for (const p of paths) {
    comment(p.op.name + (p.op.type ? ' - ' + p.op.type : ''));
    const first = p.moves[0];
    if (!tool || tool.id !== p.tool.id) {
      if (tool) { if (st.cool) line('M9'); st.cool = false; line('M5'); }
      const change = !!tool;
      tool = p.tool; rpm = null;
      // i18n-ignore: G-code comment
      if (grbl) { comment(`Tool change: T${tool.number} ${describeTool(tool).replace('⌀', 'D')}`); if (change) line('M0'); line('T' + tool.number); }
      else line('T' + tool.number + ' M6');
    }
    if (p.speeds.rpm !== rpm) { rpm = p.speeds.rpm; line('S' + rpm + ' M3'); }
    // first move: up to the clearance height, then across (both posts the same way)
    if (fanuc || lcnc) {
      if (st.h !== tool.number) { line('G0 G43 Z' + F(first.p[2]) + ' H' + tool.number); st.h = tool.number; st.g = 0; st.z = first.p[2]; }
      else move({ k: 'rapid', p: [st.x ?? first.p[0], st.y ?? first.p[1], first.p[2]] });
    } else if (st.z === null || q(st.z) !== q(first.p[2])) { line('G0 Z' + F(first.p[2])); st.g = 0; st.z = first.p[2]; }
    move({ k: 'rapid', p: first.p });
    if (coolOn && !st.cool) { line(coolOn); st.cool = true; }
    for (const m of p.moves.slice(1)) {
      if (m.k !== 'cycle') { move(m); continue; }
      if (grbl) { for (const e of expandCycle(m)) move(e); continue; }
      const code = m.kind === 'drill' ? 'G81' : m.kind === 'peck' ? 'G83' : 'G73';
      let ret = null;
      m.holes.forEach((hl, k) => {
        const r = hl.ret === 'r' ? 'G99' : 'G98';
        const rw = r !== ret ? r + ' ' : '';
        ret = r;
        if (k === 0) line(rw + code + ' X' + F(hl.at[0]) + ' Y' + F(hl.at[1]) + ' Z' + F(hl.z) + ' R' + F(hl.r) + (code !== 'G81' ? ' Q' + F(hl.q) : '') + ' F' + F(m.f));
        else {
          const prev = m.holes[k - 1];
          let w = rw + 'X' + F(hl.at[0]) + ' Y' + F(hl.at[1]);
          if (q(hl.z) !== q(prev.z)) w += ' Z' + F(hl.z);
          if (q(hl.r) !== q(prev.r)) w += ' R' + F(hl.r);
          if (code !== 'G81' && q(hl.q) !== q(prev.q)) w += ' Q' + F(hl.q);
          line(w);
        }
      });
      line('G80');
      const last = m.holes[m.holes.length - 1];
      st.g = null; st.f = q(m.f); set([last.at[0], last.at[1], last.ret === 'r' ? last.r : m.init]);
    }
  }
  if (st.cool) line('M9');
  line('M5');
  if (fanuc) { line('G28 G91 Z0.'); line('G90'); line('M30'); out.push('%'); }
  else if (lcnc) { line('G53 G0 Z0'); line('M2'); out.push('%'); }
  else line('M30');
  return { text: out.join('\n') + '\n', ext: EXT[kind], post: kind };
}

/**
 * G-code from a program. `post` is a built-in (fanuc, grbl, linuxcnc), `custom:<id>` (a post in `posts`
 * [{id, text}], the study's own), or a post definition text. The text posts run in cam-postdef.js.
 */
export function post(program, { post: kind = 'grbl', name = 'Part', posts = [] } = {}) {
  return renderPost(resolvePost(kind, posts), program, { name });
}
const cache = new Map();
/** A post key → its parsed definition (built-ins and custom texts are parsed once). */
export function resolvePost(kind, posts = []) {
  let text = BUILTIN_POSTS[kind];
  if (text === undefined && typeof kind === 'string' && kind.startsWith('custom:')) { const p = posts.find((x) => 'custom:' + x.id === kind); if (p) text = p.text; }
  if (text === undefined) throw new Error(t('xch.cam.unknown_post'));
  let d = cache.get(text);
  if (!d) { d = parsePost(text); if (cache.size > 64) cache.clear(); cache.set(text, d); }
  return d;
}

/** Every segment as CSV: op, kind, start, end, arc centre and sweep, feed (mm, mm/min). */
export function toolpathCsv(program) {
  const rows = ['op,kind,x0,y0,z0,x1,y1,z1,cx,cy,sweep_deg,feed'];
  const f = (v) => (v === undefined || v === null ? '' : String(+v.toFixed(6)));
  for (const s of segments(program.paths)) rows.push([s.op, s.k, ...s.a.map(f), ...s.b.map(f), s.c ? f(s.c[0]) : '', s.c ? f(s.c[1]) : '', s.sw !== undefined ? f((s.sw * 180) / Math.PI) : '', f(s.f)].join(','));
  return rows.join('\n') + '\n';
}
/** The program as JSON: setup, tools, and each operation's moves (canned cycles kept as cycles). */
export function toolpathJson(program) {
  return JSON.stringify({
    format: 'partcraft-toolpath', version: 1, units: 'mm', setup: program.setup,
    stock: program.model.stock, tools: program.tools,
    ops: program.paths.map((p) => ({ id: p.op.id, name: p.op.name, type: p.op.type, tool: p.tool ? p.tool.id : null, rpm: p.speeds ? p.speeds.rpm : null, error: p.error || null, moves: p.moves })),
  });
}
